#define SOLAR_OS_QEMU_HOSTFS_REG_DATA 0x100U
#define SOLAR_OS_QEMU_HOSTFS_DATA_SIZE 4096U
#define SOLAR_OS_QEMU_HOSTFS_PATH_SIZE 512U
#define SOLAR_OS_QEMU_HOSTFS_MAX_FILES 32U
#define SOLAR_OS_QEMU_HOSTFS_MAX_DIRS 8U

#define SOLAR_OS_QEMU_HOSTFS_OPEN 1U
