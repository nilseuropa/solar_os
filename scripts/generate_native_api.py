#!/usr/bin/env python3
"""Generate the native SDK and service lookup glue from public C contracts.

No firmware headers, compiler database, board settings or third-party Python
packages are used. --check also checks the released, append-only ABI baseline.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
BANNER = '/* Generated by scripts/generate_native_api.py; edit api/native/definitions. */\n'
COMMENTS = re.compile(r'/\*[\s\S]*?\*/|//[^\n]*')
TOKENS = re.compile(r'"(?:\\.|[^"\\])*"|[A-Za-z_]\w*|\d+(?:\.\d+)?[A-Za-z]*|\S')
CLIENT_HELPER_GROUPS = {
    'display': ('backlight clipboard display emotion foreground gfx input jet shell_io '
                'terminal text tui ui vector'),
    'devices': ('adc battery board bus camera charger clock controllers driver encoder expansion gpio '
                'haptic hid io modem motion motor nfc pins power pwm radio robot sensors status_led usb'),
    'media': 'audio dsp engines image inference media midi pipeline processor speech tensor vision',
    'network': ('ble contacts email http inbox link meshcore messages messaging net network osc '
                'remote sftp ssh stream wifi'),
    'storage': 'credentials document fs json manual ota packages playground settings storage xml',
}


def tokens(text):
    return TOKENS.findall(COMMENTS.sub('', text))


def signature(parts, parameter=False):
    """Keep field names, but ignore function argument names in ABI comparison.

    This deliberately accepts only ordinary public C declarators. It does not
    try to decide equivalence of different typedefs or compiler extensions.
    """
    result = list(parts)
    index = 0
    while index + 4 < len(result):
        if result[index:index+2] != ['(', '*']:
            index += 1
            continue
        close = index + 2
        if result[close] != ')': close += 1
        if result[close:close+2] != [')', '(']:
            index += 1
            continue
        depth, end = 1, close + 2
        while end < len(result) and depth:
            depth += (result[end] == '(') - (result[end] == ')')
            end += 1
        if depth: raise ValueError('unbalanced public function declaration')
        arguments, start, nested = [], close+2, 0
        for position in range(start, end-1):
            token = result[position]
            nested += (token in ('(', '[')) - (token in (')', ']'))
            if token == ',' and not nested:
                arguments.extend(signature(result[start:position], True) + [','])
                start = position+1
        arguments.extend(signature(result[start:end-1], True))
        result[close+2:end-1] = arguments
        index = close+2+len(arguments)+1
    if parameter:
        # A named callback has its identifier inside (*name), not at the end.
        for index in range(len(result)-3):
            if result[index:index+2] == ['(', '*'] and result[index+3] == ')':
                result.pop(index+2)
                break
        # Array bounds in parameters do not change C's adjusted pointer type.
        array = result.index('[') if '[' in result else len(result)
        candidate = array-1
        if candidate >= 0 and re.fullmatch(r'[A-Za-z_]\w*', result[candidate]):
            builtin = {'void','char','short','int','long','float','double','signed','unsigned',
                       'bool','size_t','va_list','const','volatile','restrict'}
            token = result[candidate]
            # Public typedef names end in _t or _fn; struct/enum tags are types.
            named = token not in builtin and not token.endswith(('_t','_fn')) and \
                (candidate == 0 or result[candidate-1] not in ('struct','enum','union'))
            if named and candidate > 0:
                result.pop(candidate)
        if '[' in result:
            # Public parameters use only a single fixed array dimension.
            begin = result.index('[')
            result[begin:] = ['*']
    return result


def typedef_ranges(source):
    """Find complete typedef declarations, including nested records."""
    for start in re.finditer(r'\btypedef\b', source):
        brace = paren = 0
        end = start.end()
        while end < len(source):
            char = source[end]
            brace += (char == '{') - (char == '}')
            paren += (char == '(') - (char == ')')
            if char == ';' and not brace and not paren:
                break
            end += 1
        yield start.start(), end


def records(text):
    """Extract typedef declarations; balance braces so nested records survive."""
    source = COMMENTS.sub('', text)
    result = {}
    for start, end in typedef_ranges(source):
        declaration = source[start+len('typedef'):end]
        name = re.search(r'([A-Za-z_]\w*)\s*$', declaration)
        callback = re.search(r'\(\s*\*\s*(\w+)\s*\)', declaration)
        if not name and callback:
            name = callback
        if not name:
            raise ValueError('unsupported public typedef: ' + declaration[:80])
        name = name[1]
        body = declaration[declaration.find('{') + 1:declaration.rfind('}')]
        table = bool(re.search(r'_api_v\d+_t$', name)) and declaration.lstrip().startswith('struct') and '{' in declaration and \
            re.match(r'\s*uint32_t\s+abi_version\s*[,;]\s*(?:uint32_t\s+)?struct_size\s*[,;]', body)
        if table:
            fields = [' '.join(signature(tokens(field))) for field in body.split(';') if tokens(field)]
            result[name] = {'table': fields}
        else:
            result[name] = {'declaration': ' '.join(signature(tokens(declaration)))}
    return result


def snapshot(headers, services):
    result = {'types': {}, 'constants': {}, 'includes': {}, 'services': {}, 'exports': {}}
    for name, source in sorted(headers.items()):
        for key, value in records(source).items():
            if key in result['types'] and result['types'][key] != value:
                raise ValueError('conflicting type: ' + key)
            result['types'][key] = value
        logical = COMMENTS.sub('', source).replace('\\\n', ' ')
        for match in re.finditer(r'^\s*#\s*define\s+(\w+)[ \t]+([^\n]+)', logical, re.M):
            value = ' '.join(tokens(match[2]))
            previous = result['constants'].get(match[1])
            if previous is None:
                result['constants'][match[1]] = value
            elif previous != value:
                variants = previous if isinstance(previous, list) else [previous]
                if value not in variants: variants.append(value)
                result['constants'][match[1]] = variants
        for match in re.finditer(r'\b(const\s+\w+\s*\*\s*(solar_os_native_\w+)\s*\([^;{}]*\)\s*);', logical):
            result['exports'][match[2]] = ' '.join(tokens(match[1]))
        result['includes'][name] = re.findall(r'^\s*#\s*include\s+[<"]([^">]+)', source, re.M)
    for service in services:
        result['services'][service['id']] = {k: service[k] for k in ('name', 'abi', 'type', 'scoped')}
    return result


def compatibility_errors(old, current):
    errors = []
    for section in ('types', 'constants', 'includes', 'services', 'exports'):
        for name, value in old.get(section, {}).items():
            new = current[section].get(name)
            if section == 'types' and 'table' in value and new and 'table' in new:
                valid = new['table'][:len(value['table'])] == value['table']
            else:
                valid = new == value
            if not valid:
                errors.append(f'incompatible {section}: {name}; add a new version instead')
    return errors


def load(root):
    base = root / 'api/native'
    services = tomllib.loads((base / 'services.toml').read_text())['service']
    headers = {p.name: p.read_text() for p in sorted((base / 'definitions').glob('*.h'))}
    # Follow only the public include closure. Private/SDK types cannot slip in.
    pending = list(headers)
    allowed = {'stdbool.h', 'stddef.h', 'stdint.h', 'stdarg.h'}
    while pending:
        name = pending.pop()
        public_source = COMMENTS.sub('', headers[name])
        if re.search(r'\b(?:CONFIG_|SOLAR_OS_PACKAGE_|SOLAR_OS_BOARD_)\w*', public_source):
            raise ValueError(f'{name}: firmware configuration in public contract')
        tracked_records = list(typedef_ranges(public_source))
        for definition in re.finditer(r'^\s*(?:struct|union|enum)\s+(?:\w+\s*)?\{', public_source, re.M):
            if not any(start <= definition.start() < end for start, end in tracked_records):
                raise ValueError(f'{name}: public records/enums must use a typedef for compatibility and layout checks')
        for dependency in re.findall(r'^\s*#\s*include\s+[<"]([^">]+)', headers[name], re.M):
            if dependency in allowed or dependency in headers:
                continue
            if '/' in dependency or not dependency.startswith('solar_os_'):
                raise ValueError(f'{name}: private/vendor include {dependency}')
            path = root / 'include' / dependency
            if not path.is_file():
                raise ValueError(f'{name}: missing public dependency {dependency}')
            headers[dependency] = path.read_text()
            pending.append(dependency)
    names, ids = set(), set()
    types = snapshot(headers, [])['types']
    for service in services:
        identity = (service['name'], service['abi'])
        if service['id'] in ids:
            raise ValueError('duplicate service identifier: ' + service['id'])
        ids.add(service['id'])
        if identity in names:
            raise ValueError('duplicate service: ' + service['name'])
        names.add(identity)
        if not re.fullmatch(r'[a-z][a-z0-9_]*', service['id']):
            raise ValueError('invalid service identifier')
        if not isinstance(service['abi'], int) or not 1 <= service['abi'] <= 0xffffffff:
            raise ValueError('invalid service ABI')
        if not isinstance(service['scoped'], bool):
            raise ValueError('service scope must be explicit')
        if not re.fullmatch(r'[a-z][a-z0-9_.]{0,46}', service['name']):
            raise ValueError('invalid service name')
        if service['type'] not in types or 'table' not in types[service['type']]:
            raise ValueError('service must name a versioned public table: ' + service['id'])
        if service['header'] not in headers or service['type'] not in records(headers[service['header']]):
            raise ValueError('service table must be declared by its public header')
        constants = snapshot({service['header']: headers[service['header']]}, [])['constants']
        prefixes = [name[:-8] for name, value in constants.items()
                    if name.endswith('_SERVICE') and value == json.dumps(service['name'])]
        if not any(constants.get(prefix+'_ABI') == str(service['abi'])+'U' for prefix in prefixes):
            raise ValueError('service identity differs from its public constants: ' + service['id'])
    return headers, services


def outputs(root, headers, services):
    result = {}
    for path in sorted((root / 'api/native/definitions').glob('*.h')):
        result[Path('include') / path.name] = BANNER + path.read_text()
    client = [BANNER, '#pragma once\n', '#include "solar_os_native_abi.h"\n',
              '#include <stdbool.h>\n#include <string.h>\n']
    for header in sorted({s['header'] for s in services}):
        client.append(f'#include "{header}"\n')
    client.append('''
typedef const void *(*solar_os_native_lookup_fn)(const char *, uint32_t, uint32_t);
/* Size expressions are valid for either target and never evaluate a pointer. */
#define SOLAR_OS_NATIVE_THROUGH(type, member) \\
    ((uint32_t)(offsetof(type, member) + sizeof(((type *)0)->member)))

static inline bool solar_os_native_api_matches(const void *api, uint32_t abi, uint32_t size)
{
    /* get_service returns a readable two-word header or NULL. memcpy avoids
     * strict-aliasing assumptions about unrelated service table types. */
    uint32_t header[2];
    if (!api) return false;
    memcpy(header, api, sizeof(header));
    return header[0] == abi && header[1] >= size && size >= sizeof(header);
}

static inline const solar_os_native_host_api_v1_t *solar_os_native_host_get(uint32_t minimum_size)
{
    const solar_os_native_host_api_v1_t *host = solar_os_native_host_v1();
    return solar_os_native_api_matches(host, SOLAR_OS_NATIVE_ABI_VERSION, minimum_size) ? host : NULL;
}
''')
    # Keep the embedded on-device C SDK small while emitting ordinary typed
    # inline functions. Macro definitions are private to this generated header.
    client.append(r'''
#define SOLAR_OS_NATIVE_DECLARE_GET(id, name, type, version) \
static inline const type *solar_os_native_##id##_get( \
    solar_os_native_lookup_fn lookup, uint32_t minimum_size) \
{ \
    if (!lookup || minimum_size < 8U) return NULL; \
    const void *api = lookup(name, version, minimum_size); \
    return solar_os_native_api_matches(api, version, minimum_size) ? (const type *)api : NULL; \
}
#define SOLAR_OS_NATIVE_DECLARE_HAS(id, type, version, method) \
static inline bool solar_os_native_##id##_has_##method(const type *api) \
{ \
    return solar_os_native_api_matches(api, version, SOLAR_OS_NATIVE_THROUGH(type, method)) && \
        api->method != NULL; \
}
''')
    types = snapshot(headers, [])['types']
    # The root host includes these anchors even after its final table moves to
    # a separate provider. Regenerate them empty instead of leaving stale C.
    groups = {'root_early': [], 'root_late': []}
    client_headers = {name: [] for name in ('core', *sorted(CLIENT_HELPER_GROUPS))}
    group_by_namespace = {namespace: group for group, namespaces in CLIENT_HELPER_GROUPS.items()
                          for namespace in namespaces.split()}
    for service in services:
        ident, typ, abi = service['id'], service['type'], service['abi']
        declarations = [f'\nSOLAR_OS_NATIVE_DECLARE_GET({ident}, "{service["name"]}", {typ}, {abi}U)\n']
        methods = []
        for field in types[typ]['table']:
            match = re.search(r'\( \* (\w+) \)', field)
            if match:
                methods.append(match[1])
        if methods:
            declarations.append('#define SOLAR_OS_NATIVE_CLIENT_METHOD(method) '
                                f'SOLAR_OS_NATIVE_DECLARE_HAS({ident}, {typ}, {abi}U, method)\n')
            declarations.append('#define SOLAR_OS_NATIVE_CLIENT_METHODS(M) \\\n')
            declarations.append(' \\\n'.join(f'    M({method})' for method in methods) + '\n')
            declarations.append('SOLAR_OS_NATIVE_CLIENT_METHODS(SOLAR_OS_NATIVE_CLIENT_METHOD)\n'
                                '#undef SOLAR_OS_NATIVE_CLIENT_METHODS\n'
                                '#undef SOLAR_OS_NATIVE_CLIENT_METHOD\n')
        namespace = service['name'].partition('.')[0]
        client_headers[group_by_namespace.get(namespace, 'core')].extend(declarations)
        if service.get('provider'):
            groups.setdefault(service['provider'], []).append(service)
    sdk_header = (root / 'include/solar_os_native_sdk.h').read_text()
    limit = int(re.search(r'^#define SOLAR_OS_NATIVE_SDK_FILE_MAX (\d+)U$', sdk_header, re.M)[1])
    for group, declarations in client_headers.items():
        if not declarations:
            continue
        name = f'solar_os_native_client_{group}.h'
        source = BANNER + '#pragma once\n/* Included through solar_os_native_client.h. */\n' + ''.join(declarations)
        if len(source.encode()) > limit:
            raise ValueError(f'{name} exceeds the {limit}-byte SDK file limit')
        result[Path('include') / name] = source
        client.append(f'#include "{name}"\n')
    client.append('\n#undef SOLAR_OS_NATIVE_DECLARE_GET\n#undef SOLAR_OS_NATIVE_DECLARE_HAS\n')
    result[Path('include/solar_os_native_client.h')] = ''.join(client)
    for group, entries in groups.items():
        dispatch = [BANNER, '/* Included inside a provider; name/abi/minimum are in scope. */\n']
        for entry in entries:
            if entry.get('gate'):
                dispatch.append(f"#if {entry['gate']}\n")
            dispatch.append(f'_Static_assert(__builtin_types_compatible_p(__typeof__({entry["table"]}), '
                            f'const {entry["type"]}), "native service table type");\n')
            dispatch.append(f'if (name && !strcmp(name, "{entry["name"]}") && abi == {entry["abi"]}U &&\n'
                            f'    minimum <= sizeof({entry["table"]})) return &{entry["table"]};\n')
            if entry.get('gate'):
                dispatch.append('#endif\n')
        result[Path(f'src/services/generated/native_{group}_dispatch.inc')] = ''.join(dispatch)
    descriptors = [BANNER]
    for service in services:
        descriptors.append(f'{{"{service["name"]}", {service["abi"]}U, '
                           f'{"SOLAR_OS_NATIVE_SYSTEM_SCOPED" if service["scoped"] else "0U"}}},\n')
    result[Path('src/services/generated/native_service_descriptors.inc')] = ''.join(descriptors)
    providers = tomllib.loads((root/'api/native/services.toml').read_text()).get('provider', [])
    parents = {'root': []}
    for provider in providers:
        if not re.fullmatch(r'[a-z][a-z0-9_]*', provider['parent']) or \
            not re.fullmatch(r'solar_os_native_\w+_get_service', provider['getter']):
            raise ValueError('invalid native provider wiring')
        parents.setdefault(provider['parent'], []).append(provider)
    for parent, entries in parents.items():
        source = [BANNER]
        if len(entries) == 1:
            entry = entries[0]
            if entry.get('gate'): source.append(f"#if {entry['gate']}\n")
            source.append(f'{{\n    const void *provided = {entry["getter"]}(name, abi, minimum);\n'
                          '    if (provided) return provided;\n}\n')
            if entry.get('gate'): source.append('#endif\n')
        elif entries:
            source.append('static const void *(*const providers[])(const char *, uint32_t, uint32_t) = {\n')
            for entry in entries:
                if entry.get('gate'): source.append(f"#if {entry['gate']}\n")
                source.append(f'    {entry["getter"]},\n')
                if entry.get('gate'): source.append('#endif\n')
            source.append('    NULL,\n};\n'
                          'for (size_t i = 0; providers[i]; ++i) {\n'
                          '    const void *provided = providers[i](name, abi, minimum);\n'
                          '    if (provided) return provided;\n}\n')
        result[Path(f'src/services/generated/native_{parent}_providers.inc')] = ''.join(source)
    root_headers = [BANNER, '/* Root provider declarations follow the same registry as dispatch. */\n']
    for entry in parents['root']:
        header = entry['getter'].removesuffix('_get_service') + '.h'
        root_headers.append(f'#include "../{header}"\n')
    result[Path('src/services/generated/native_root_provider_headers.inc')] = ''.join(root_headers)
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--update-lock', action='store_true', help='Record compatible additions only')
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--baseline', type=Path, help='Also check a prior release/base-branch ABI lock')
    args = parser.parse_args(argv)
    root = args.root.resolve()
    metadata = tomllib.loads((root / 'api/native/services.toml').read_text())
    packages = tomllib.loads((root / 'packages/solar_os_packages.toml').read_text())['packages']
    gates = {'SOLAR_OS_PACKAGE_' + name.upper() for name in packages}
    for entry in metadata['service'] + metadata.get('provider', []):
        if entry.get('gate') and entry['gate'] not in gates:
            raise ValueError('unknown native service package gate: ' + entry['gate'])
    headers, services = load(root)
    current = snapshot(headers, services)
    if args.baseline:
        errors = compatibility_errors(json.loads(args.baseline.read_text()), current)
        if errors:
            raise ValueError('\n'.join(errors))
    lock = root / 'api/native/abi-lock.json'
    if lock.exists():
        errors = compatibility_errors(json.loads(lock.read_text()), current)
        if errors:
            raise ValueError('\n'.join(errors))
    elif not args.update_lock:
        raise ValueError('ABI baseline missing; initialize with --update-lock')
    if args.check and args.update_lock:
        parser.error('--check and --update-lock cannot be combined')
    stale = []
    generated = outputs(root, headers, services)
    for path in (root / 'include').glob('solar_os_native_client_*.h'):
        relative = path.relative_to(root)
        if relative not in generated and path.read_text().startswith(BANNER):
            if args.check:
                stale.append(str(relative))
            else:
                path.unlink()
    for relative, source in generated.items():
        path = root / relative
        if path.is_file() and path.read_text() == source:
            continue
        if args.check:
            stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)
    if stale:
        raise ValueError('regenerate native API: ' + ', '.join(stale))
    if args.update_lock:
        lock.write_text(json.dumps(current, indent=2, sort_keys=True) + '\n')
    print(f'native API: {len(services)} services; SDK and ABI baseline checked')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
