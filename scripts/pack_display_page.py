#!/usr/bin/env python3
"""Pack the display server's exact HTML reply into a generated firmware header."""

import argparse
import ast
from pathlib import Path
import re
import zlib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()

    # Each source line is an ordinary C string literal. Preserve every byte
    # of the concatenated reply, including escapes inside its JavaScript.
    lines = args.source.read_text(encoding="utf-8").splitlines()
    if not lines or any(not re.fullmatch(r'"(?:[^"\\]|\\.)*"', line.strip()) for line in lines):
        raise ValueError("invalid display page source")
    page = "".join(ast.literal_eval(line.strip()) for line in lines).encode("utf-8")
    packed = zlib.compress(page, 9)
    if len(packed) >= len(page):
        raise ValueError("packed display page is larger than its source")

    header = ["/* Generated by scripts/pack_display_page.py. */", "#pragma once",
              "#include <stdint.h>", f"#define SOLAR_OS_DISPLAY_PAGE_BYTES {len(page)}U",
              "static const uint8_t display_page_packed[] = {"]
    for offset in range(0, len(packed), 16):
        header.append("    " + ", ".join(f"0x{byte:02x}" for byte in packed[offset:offset + 16]) + ",")
    content = "\n".join([*header, "};", ""])
    if not args.header.exists() or args.header.read_text() != content:
        args.header.write_text(content)


if __name__ == "__main__":
    main()
