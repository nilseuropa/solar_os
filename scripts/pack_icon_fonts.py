#!/usr/bin/env python3
"""Pack the large Open Iconic U8g2 faces into bounded, lossless LZ4 blocks."""

import argparse
import ast
from pathlib import Path
import re

from pack_lz4 import compress_block


ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / 'components/u8g2/src/fonts'
OUTPUT = ROOT / 'src/services/generated/solar_os_icon_fonts.inc'
HEADER_BYTES = 23
BLOCK_BYTES = 1024
ICON_COUNT = 223
FIRST_ENCODING = 64
SCALES = (4, 6, 8)


def read_font(scale):
    source = (FONT_DIR / f'u8g2_font_open_iconic_all_{scale}x_t.c').read_text()
    declared_size, initializer = re.search(
        r'\[(\d+)\][^\n]*=\s*((?:"(?:[^"\\]|\\.)*"\s*)+);', source).groups()
    parts = re.findall(r'"(?:[^"\\]|\\.)*"', initializer)
    data = ''.join(ast.literal_eval(part) for part in parts).encode('latin1') + b'\0'
    if len(data) != int(declared_size) or data[0] != ICON_COUNT:
        raise ValueError(f'unexpected U8g2 font size at scale {scale}')
    return data


def read_glyphs(data):
    glyphs = []
    offset = HEADER_BYTES
    while data[offset + 1]:
        code, size = data[offset:offset + 2]
        if code != FIRST_ENCODING + len(glyphs) or size <= 2:
            raise ValueError('unexpected single-byte Open Iconic record')
        glyphs.append(data[offset + 2:offset + size])
        offset += size

    offset = HEADER_BYTES + int.from_bytes(data[21:23], 'big')
    offset += int.from_bytes(data[offset:offset + 2], 'big')
    while data[offset:offset + 2] != b'\0\0':
        code = int.from_bytes(data[offset:offset + 2], 'big')
        size = data[offset + 2]
        if code != FIRST_ENCODING + len(glyphs) or size <= 3:
            raise ValueError('unexpected Unicode Open Iconic record')
        glyphs.append(data[offset + 3:offset + size])
        offset += size
    if len(glyphs) != ICON_COUNT or any(len(glyph) > 253 for glyph in glyphs):
        raise ValueError('Open Iconic glyph layout changed')
    return glyphs


def blocks_for(glyphs):
    block = bytearray()
    for index, glyph in enumerate(glyphs):
        if len(block) + 1 + len(glyph) > BLOCK_BYTES:
            yield index - 1, bytes(block)
            block.clear()
        block.append(len(glyph))
        block.extend(glyph)
    yield len(glyphs) - 1, bytes(block)


def emit_bytes(name, data):
    yield f'static const uint8_t {name}[] ='
    for offset in range(0, len(data), 20):
        yield '    "' + ''.join(f'\\x{value:02x}' for value in data[offset:offset + 20]) + '"'
    yield '    ;'


def generate():
    yield '/* Generated by scripts/pack_icon_fonts.py from the Open Iconic U8g2 fonts.'
    yield ' * Open Iconic glyphs are distributed under the SIL Open Font License. */'
    yield f'#define SOLAR_OS_ICON_BLOCK_BYTES {BLOCK_BYTES}U'
    for scale in SCALES:
        original = read_font(scale)
        pixels = scale * 8
        prefix = f'icon_{pixels}px'
        packed = bytearray()
        blocks = []
        for last, raw in blocks_for(read_glyphs(original)):
            blocks.append((len(packed), len(raw), last))
            packed.extend(compress_block(raw))
        blocks.append((len(packed), 0, 0))  # End offset of the final block.
        if len(packed) >= 65536:
            raise ValueError('compressed offsets do not fit')
        yield from emit_bytes(f'{prefix}_header', original[:HEADER_BYTES])
        yield from emit_bytes(f'{prefix}_packed', packed)
        yield f'static const icon_font_block_t {prefix}_blocks[] = {{'
        for offset, size, last in blocks:
            yield f'    {{{offset}, {size}, {last}}},'
        yield '};'
    yield 'static const icon_font_t large_icon_fonts[] = {'
    for scale in SCALES:
        prefix = f'icon_{scale * 8}px'
        yield f'    {{{prefix}_header, {prefix}_packed, {prefix}_blocks}},'
    yield '};'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = '\n'.join(generate()) + '\n'
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit('Open Iconic packed font data is stale')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
